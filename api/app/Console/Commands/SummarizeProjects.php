<?php

namespace App\Console\Commands;

use App\Actions\ProjectSummaries\RequestProjectSummary;
use App\Ai\AiBudget;
use App\Ai\Exceptions\AiBudgetExceeded;
use App\Enums\Permission;
use App\Models\Organization;
use App\Models\Project;
use App\Models\Role;
use App\Support\CurrentOrganization;
use Illuminate\Console\Command;
use Illuminate\Database\Eloquent\Builder;

/**
 * Backfill: queue summaries for projects that have a description but never had
 * a summary (e.g. created before AI was on). Each organization runs in its own
 * scope. Only projects whose creator is still a member allowed to use AI
 * (ai.use) are summarized, as the automatic summary on create would have been.
 */
class SummarizeProjects extends Command
{
    protected $signature = 'ai:summarize-projects
        {--organization=* : Only these organization ids (default: all)}
        {--limit=50 : Most summaries to queue in total}
        {--dry-run : Only count the projects that would be summarized}';

    protected $description = 'Queue AI summaries for projects that have a description and no summary (stops queueing for an organization whose budget is already spent)';

    public function handle(CurrentOrganization $currentOrganization, RequestProjectSummary $requestSummary, AiBudget $budget): int
    {
        $limit = (int) $this->option('limit');
        $ids = array_map(intval(...), (array) $this->option('organization'));
        $dryRun = (bool) $this->option('dry-run');

        if ($limit < 1) {
            $this->error('--limit must be at least 1.');

            return self::INVALID;
        }

        $remaining = $limit;
        $total = 0;

        $organizations = Organization::query()->when($ids !== [], fn ($query) => $query->whereKey($ids))->lazyById();

        foreach ($organizations as $organization) {
            if ($remaining === 0) {
                break;
            }

            $count = $currentOrganization->runAs($organization, function () use ($organization, $requestSummary, $budget, $remaining, $dryRun) {
                $label = "{$organization->name} (#{$organization->id})";

                // Scoped to this organization by BelongsToOrganization.
                $candidates = fn (): Builder => Project::query()
                    ->whereNotNull('description')
                    ->where('description', '!=', '')
                    ->whereDoesntHave('summaries');

                $aiRoleIds = Role::query()->get()->filter(fn (Role $role) => $role->has(Permission::AiUse))->modelKeys();
                $allowedCreatorIds = $organization->members()->wherePivotIn('role_id', $aiRoleIds)->pluck('users.id');

                $projects = $candidates()->whereIn('created_by', $allowedCreatorIds)->with('creator')->orderBy('id')->limit($remaining)->get();
                $notAllowed = $candidates()->where(fn ($query) => $query->whereNull('created_by')->orWhereNotIn('created_by', $allowedCreatorIds))->count();
                $skipped = $notAllowed > 0 ? ", skipped {$notAllowed} whose creator can no longer use AI" : '';

                if ($projects->isEmpty()) {
                    if ($notAllowed > 0) {
                        $this->line("{$label}: nothing to queue{$skipped}.");
                    }

                    return 0;
                }

                if ($budget->exceeded($organization)) {
                    $this->line("{$label}: skipped, the monthly AI budget is used up.");

                    return 0;
                }

                if ($dryRun) {
                    $this->line("{$label}: would queue {$projects->count()}{$skipped}.");

                    return $projects->count();
                }

                $queued = 0;

                foreach ($projects as $project) {
                    try {
                        // Billed to the creator; the audit log shows it as a system request.
                        $requestSummary->handle($project, $project->creator, source: 'backfill');
                    } catch (AiBudgetExceeded) {
                        $this->line("{$label}: queued {$queued}, then stopped: the monthly AI budget is used up.");

                        return $queued;
                    }

                    $queued++;
                }

                $this->line("{$label}: queued {$queued}{$skipped}.");

                return $queued;
            });

            $remaining -= $count;
            $total += $count;
        }

        $this->info($dryRun ? "Would queue {$total} summaries." : "Queued {$total} summaries.");

        if (! $dryRun && $total > 0) {
            // The budget only counts calls already made: jobs that run once it's used up fail as budget_exceeded.
            $this->line('Summaries are generated by the queue worker; any that run after an organization\'s budget is used up fail.');
        }

        return self::SUCCESS;
    }
}
